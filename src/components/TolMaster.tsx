const formatRunTime = (timestamp: number | null) => {
  if (!timestamp) return 'Not run';
  return new Date(timestamp).toLocaleString([], {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit'
  });
};

const formatDistributionLabel = (distribution: DistributionType) => {
  switch (distribution) {
    case 'Normal':
      return 'NORM';
    case 'Normal(Sort)':
      return 'SORT';
    case 'Uniform':
      return 'UNIF';
    case 'Fixed':
      return 'FIXD';
    case 'Empirical':
      return 'EMPR';
    default:
      return distribution.toUpperCase();
  }
};

let _normalSpare: number | null = null;
const randomNormal = (mean: number, stdDev: number) => {
  if (_normalSpare !== null) {
    const val = mean + _normalSpare * stdDev;
    _normalSpare = null;
    return val;
  }
  let u = 0, v = 0;
  while (u === 0) u = Math.random();
  while (v === 0) v = Math.random();
  const mag = Math.sqrt(-2.0 * Math.log(u));
  _normalSpare = mag * Math.sin(2.0 * Math.PI * v);
  return mean + mag * Math.cos(2.0 * Math.PI * v) * stdDev;
};

const randomBeta05 = () => {
  // Beta(0.5, 0.5) generator (Arcsine distribution)
  // Method: sin^2(Theta) where Theta is Uniform(0, PI/2)
  // Or simply: sin^2( (PI/2) * rand ) ? No, standard method is sin^2(PI/2 * U) is not quite right for Beta(0.5,0.5).
  // Actually, Beta(0.5, 0.5) is related to sin^2.
  // Let U ~ Uniform(0, 1). X = sin^2( (PI/2) * U ) is NOT Beta(0.5, 0.5).
  // Correct generation for Beta(alpha, beta):
  // For alpha=0.5, beta=0.5:
  // X = sin^2( 2 * PI * U ) ? No.
  // Let's use the standard Gamma method or a specific transformation.
  // For Beta(0.5, 0.5): X = sin^2( Phi ) where Phi is Uniform(0, PI/2) IS correct?
  // Let's check: If X ~ Beta(1/2, 1/2), then X is Arcsine distributed on [0,1].
  // CDF is (2/PI) * arcsin(sqrt(x)).
  // Inverse CDF method: u = (2/PI) * arcsin(sqrt(x)) => x = sin^2(u * PI / 2).
  // So yes, if U ~ Uniform(0, 1), then X = sin^2(U * PI / 2) follows Beta(0.5, 0.5).
  return Math.pow(Math.sin(Math.random() * Math.PI / 2), 2);
};

// Empirical sampler: Bootstrap resampling from measured data
// Preserves skew, tails, and multimodality without smoothing or fitting
const sampleEmpirical = (model: EmpiricalModel): number => {
  const i = Math.floor(Math.random() * model.n);
  return model.samples[i];
};

const calculateSigma = (tolPlus: number, tolMinus: number, dist: DistributionType, cp?: number): number => {
  if (dist === 'Fixed') return 0;
  const totalRange = tolPlus + tolMinus;
  const halfRange = totalRange / 2;

  if (dist === 'Uniform') {
    return totalRange / Math.sqrt(12);
  }

  if (cp && cp > 0) {
    return halfRange / (3 * cp);
  } else {
    return halfRange / 3;
  }
};

const calculateEffectiveMean = (nominal: number, tolPlus: number, tolMinus: number): number => {
  return nominal + (tolPlus - tolMinus) / 2;
};

// Direction-aware stats for a Simple item.
//
// The sign of `nominal` encodes the STACK DIRECTION, while the UI shows and
// edits the magnitude (|nominal|) with tolPlus/tolMinus attached to THAT
// magnitude. A part entered as "- 13.2 (+0.6/-0)" is physically 13.2..13.8
// pointing in the negative direction, so it contributes -13.8..-13.2.
//
// Adding tolPlus straight onto the signed nominal (nominal + tolPlus) pushes a
// negative-direction part towards -12.6 instead: the exact opposite of intent.
// Symmetric tolerances mask the error, which is why it went unnoticed. Every
// consumer (Monte Carlo, worst case, solver) must go through here.
const signedStats = (item: { nominal: number; tolPlus: number; tolMinus: number }) => {
  const sign = item.nominal < 0 ? -1 : 1;
  return {
    sign,
    mean: item.nominal + sign * (item.tolPlus - item.tolMinus) / 2,
    min: sign > 0 ? item.nominal - item.tolMinus : item.nominal - item.tolPlus,
    max: sign > 0 ? item.nominal + item.tolPlus : item.nominal + item.tolMinus
  };
};

// Direction-aware asymmetric-tolerance offset only (no nominal), same convention
// as signedStats().
const signedMeanOffset = (item: { nominal: number; tolPlus: number; tolMinus: number }): number =>
  (item.nominal < 0 ? -1 : 1) * (item.tolPlus - item.tolMinus) / 2;

const calculateFitShiftVariance = (fitParams: FitParams): number => {
  const holeMean = calculateEffectiveMean(fitParams.holeNom, fitParams.holeTolPlus, fitParams.holeTolMinus);
  const shaftMean = calculateEffectiveMean(fitParams.shaftNom, fitParams.shaftTolPlus, fitParams.shaftTolMinus);
  const holeSigma = calculateSigma(fitParams.holeTolPlus, fitParams.holeTolMinus, fitParams.holeDist, fitParams.holeCP);
  const shaftSigma = calculateSigma(fitParams.shaftTolPlus, fitParams.shaftTolMinus, fitParams.shaftDist, fitParams.shaftCP);
  const muGap = holeMean - shaftMean;
  const gapSecondMomentApprox = (muGap * muGap) + (holeSigma * holeSigma) + (shaftSigma * shaftSigma);

  // Analytic RSS/sensitivity use the untruncated E[gap^2] approximation.
  // FitShift interference is handled separately by Monte Carlo failure accounting.
  return fitParams.shiftDist === 'Beta0.5'
    ? gapSecondMomentApprox / 8
    : gapSecondMomentApprox / 12;
};

// Clear compressionTargetId when it no longer points at a valid, selectable
// target: a deleted/missing item, or a FitShift item (whose `nominal` the sampler
// ignores, so it can never act as a real compression denominator). Centralised
// here and applied on every load/import path so a dangling or invalid reference
// can never reach the Monte Carlo core, where a ~0 denominator would invalidate
// every sample and be misread as a total-failure run.
const normalizeCompressionTarget = <T extends { compressionTargetId?: string | null; items: ToleranceItem[] }>(project: T): T => {
  const id = project.compressionTargetId;
  if (!id) return project;
  const target = project.items.find(it => it.id === id);
  if (!target || target.type === 'FitShift') {
    return { ...project, compressionTargetId: null };
  }
  return project;
};

const getWarning = (valStr: string, type: 'Tolerance'): string | null => {
  if (/^0\d+/.test(valStr)) {
    return "Suspected missing decimal point (e.g. 0.15?)";
  }
  const val = parseFloat(valStr);
  if (!isNaN(val) && val > 3.0) {
    return "Large tolerance value detected (> 3.0). Verify if correct.";
  }
  return null;
};

// Inverse Standard Normal Distribution (Acklam's approximation)
// Used to convert yield rate back to equivalent CP
const normSInv = (p: number): number => {
  const a1 = -3.969683028665376e+01;
  const a2 = 2.209460984245205e+02;
  const a3 = -2.759285104469687e+02;
  const a4 = 1.383577518672690e+02;
  const a5 = -3.066479806614716e+01;
  const a6 = 2.506628277459239e+00;

  const b1 = -5.447609879822406e+01;
  const b2 = 1.615858368580409e+02;
  const b3 = -1.556989798598866e+02;
  const b4 = 6.680131188771972e+01;
  const b5 = -1.328068155288572e+01;

  const c1 = -7.784894002430293e-03;
  const c2 = -3.223964580411365e-01;
  const c3 = -2.400758277161838e+00;
  const c4 = -2.549732539343734e+00;
  const c5 = 4.374664141464968e+00;
  const c6 = 2.938163982698783e+00;

  const d1 = 7.784695709041462e-03;
  const d2 = 3.224671290700398e-01;
  const d3 = 2.445134137142996e+00;
  const d4 = 3.754408661907416e+00;

  const p_low = 0.02425;
  const p_high = 1 - p_low;

  let q, r;

  if (p < 0 || p > 1) {
    return NaN;
  } else if (p < p_low) {
    q = Math.sqrt(-2 * Math.log(p));
    return (((((c1 * q + c2) * q + c3) * q + c4) * q + c5) * q + c6) /
      ((((d1 * q + d2) * q + d3) * q + d4) * q + 1);
  } else if (p <= p_high) {
    q = p - 0.5;
    r = q * q;
    return (((((a1 * r + a2) * r + a3) * r + a4) * r + a5) * r + a6) * q /
      (((((b1 * r + b2) * r + b3) * r + b4) * r + b5) * r + 1);
  } else {
    q = Math.sqrt(-2 * Math.log(1 - p));
    return -(((((c1 * q + c2) * q + c3) * q + c4) * q + c5) * q + c6) /
      ((((d1 * q + d2) * q + d3) * q + d4) * q + 1);
  }
};

// Monte Carlo sample generator (pure). Builds per-item params then runs the
// stack-up loop. Extracted from runSimulation so the nominal optimizer can
// evaluate arbitrary candidate items. Behaviour must stay identical to the
// inline loop it replaces.
interface MonteCarloOptions {
  N: number;
  isCompressionMode: boolean;
  compressionTargetId: string | null;
}

const runMonteCarloSamples = (
  items: ToleranceItem[],
  opts: MonteCarloOptions
): { samples: Float32Array; gapStats: { mean: number; min: number; max: number } | null; targetStraddlesZero: boolean } => {
  const { N, isCompressionMode, compressionTargetId } = opts;
  const samples = new Float32Array(N);

  const simpleItemParams = items.map(item => {
    if (item.type === 'FitShift' && item.fitParams) {
      return {
        type: 'FitShift',
        fit: {
          hMean: calculateEffectiveMean(item.fitParams.holeNom, item.fitParams.holeTolPlus, item.fitParams.holeTolMinus),
          hSigma: calculateSigma(item.fitParams.holeTolPlus, item.fitParams.holeTolMinus, item.fitParams.holeDist, item.fitParams.holeCP),
          sMean: calculateEffectiveMean(item.fitParams.shaftNom, item.fitParams.shaftTolPlus, item.fitParams.shaftTolMinus),
          sSigma: calculateSigma(item.fitParams.shaftTolPlus, item.fitParams.shaftTolMinus, item.fitParams.shaftDist, item.fitParams.shaftCP),
          hDist: item.fitParams.holeDist,
          sDist: item.fitParams.shaftDist,
          hMin: item.fitParams.holeNom - item.fitParams.holeTolMinus,
          hMax: item.fitParams.holeNom + item.fitParams.holeTolPlus,
          sMin: item.fitParams.shaftNom - item.fitParams.shaftTolMinus,
          sMax: item.fitParams.shaftNom + item.fitParams.shaftTolPlus,
          shiftDist: item.fitParams.shiftDist || 'Uniform'
        }
      };
    }

    // Direction-aware: tolPlus/tolMinus belong to the displayed magnitude, so a
    // negative-direction item has its two tolerance sides swapped in stack space.
    const st = signedStats(item);

    return {
      type: 'Simple',
      mean: st.mean,
      sigma: calculateSigma(item.tolPlus, item.tolMinus, item.distribution, item.cp),
      dist: item.distribution,
      min: st.min,
      max: st.max,
      val: item.nominal,
      sign: st.sign,
      enableMeanDrift: item.distribution === 'Empirical' ? false : (item.enableDynamicMeanShift || false),
      nominalMean: st.mean,
      empiricalModel: item.empiricalModel
    };
  });

  let gapSum = 0;
  let gapMin = Infinity;
  let gapMax = -Infinity;
  let validGapCount = 0;

  // Compression-target sign/scale tracking. The ratio blows up as the target
  // approaches zero, and Math.abs() hides a sign flip, so we (a) scale the
  // "undefined" cutoff to the target's own magnitude instead of a fixed 1e-6,
  // and (b) flag when the target distribution straddles zero.
  let targetMin = Infinity;
  let targetMax = -Infinity;
  let denomCutoff = 0.000001;
  if (isCompressionMode && compressionTargetId) {
    const tItem = items.find(it => it.id === compressionTargetId);
    if (tItem) {
      // Scale of the target: |nominal| plus its tolerance span, floored so a
      // zero-nominal target still gets a sane cutoff.
      const tScale = Math.max(
        Math.abs(tItem.nominal) + Math.abs(tItem.tolPlus) + Math.abs(tItem.tolMinus),
        1e-9
      );
      denomCutoff = Math.max(1e-6, tScale * 1e-4);
    }
  }

  for (let i = 0; i < N; i++) {
    let stackSum = 0;
    let targetItemValue = 0;
    let fitShiftInterference = false;

    for (let j = 0; j < simpleItemParams.length; j++) {
      const p: any = simpleItemParams[j];
      let itemVal = 0;

      if (p.type === 'FitShift') {
        let holeVal = 0;
        if (p.fit.hDist === 'Normal') holeVal = randomNormal(p.fit.hMean, p.fit.hSigma);
        else if (p.fit.hDist === 'Uniform') holeVal = Math.random() * (p.fit.hMax - p.fit.hMin) + p.fit.hMin;
        else holeVal = p.fit.hMean;

        let shaftVal = 0;
        if (p.fit.sDist === 'Normal') shaftVal = randomNormal(p.fit.sMean, p.fit.sSigma);
        else if (p.fit.sDist === 'Uniform') shaftVal = Math.random() * (p.fit.sMax - p.fit.sMin) + p.fit.sMin;
        else shaftVal = p.fit.sMean;

        const gap = holeVal - shaftVal;
        if (gap < 0) {
          fitShiftInterference = true;
          break;
        }

        if (p.fit.shiftDist === 'Beta0.5') {
          const betaVal = randomBeta05();
          itemVal = (betaVal * gap) - (gap / 2);
        } else {
          itemVal = Math.random() * gap - gap / 2;
        }

        // A FitShift item can never be the compression target/denominator: its
        // `nominal` isn't a controllable dimension (the denominator would be the
        // whole hole–shaft gap), so it is banned in the UI and by
        // normalizeCompressionTarget on every load/import. No target-tracking
        // branch here — keeping one would imply a support path that does not
        // (and must not) exist.
      } else {
        if (p.dist === 'Normal') {
          let currentMean = p.mean;
          if (p.enableMeanDrift) {
            const driftMag = 1.5 * p.sigma;
            currentMean = p.nominalMean + (Math.random() * 2 - 1) * driftMag;
          }
          itemVal = randomNormal(currentMean, p.sigma);
        } else if (p.dist === 'Normal(Sort)') {
          let currentMean = p.mean;
          if (p.enableMeanDrift) {
            const driftMag = 1.5 * p.sigma;
            currentMean = p.nominalMean + (Math.random() * 2 - 1) * driftMag;
          }

          const aCdf = normSDist((p.min - currentMean) / p.sigma);
          const bCdf = normSDist((p.max - currentMean) / p.sigma);
          const u = aCdf + Math.random() * (bCdf - aCdf);
          itemVal = Math.max(p.min, Math.min(p.max, currentMean + p.sigma * normSInv(u)));
        } else if (p.dist === 'Uniform') {
          itemVal = Math.random() * (p.max - p.min) + p.min;
        } else if (p.dist === 'Empirical' && p.empiricalModel) {
          const empiricalSample = sampleEmpirical(p.empiricalModel);
          // The measured deviation is in physical (magnitude) space; project it
          // onto the stack direction before offsetting by the signed mean.
          itemVal = p.sign * (empiricalSample - p.empiricalModel.mean) + p.mean;

          if (p.enableMeanDrift) {
            const driftMag = 1.5 * p.empiricalModel.std;
            itemVal += (Math.random() * 2 - 1) * driftMag;
          }
        } else {
          itemVal = p.val;
        }

        if (isCompressionMode && items[j].id === compressionTargetId) {
          targetItemValue = itemVal;
          if (itemVal < targetMin) targetMin = itemVal;
          if (itemVal > targetMax) targetMax = itemVal;
        }
      }

      stackSum += itemVal;
    }

    if (fitShiftInterference) {
      samples[i] = Number.NaN;
      continue;
    }

    if (isCompressionMode) {
      gapSum += stackSum;
      if (stackSum < gapMin) gapMin = stackSum;
      if (stackSum > gapMax) gapMax = stackSum;
      validGapCount++;
    }

    if (isCompressionMode && compressionTargetId) {
      const denom = Math.abs(targetItemValue);
      // Ratio undefined when the compression target ≈ 0 (relative cutoff, scaled
      // to the target's own magnitude). Encoded as -Infinity — a DISTINCT
      // sentinel from the NaN used for FitShift interference — so downstream can
      // report the two invalid causes separately. Note: like NaN, these samples
      // are excluded from mean/σ but DO count against yield/PPM (they are real
      // invalid outcomes, not passes).
      samples[i] = denom < denomCutoff ? Number.NEGATIVE_INFINITY : (stackSum / denom) * 100;
    } else {
      samples[i] = stackSum;
    }
  }

  const gapStats = (isCompressionMode && validGapCount > 0)
    ? { mean: gapSum / validGapCount, min: gapMin, max: gapMax }
    : null;

  const targetStraddlesZero = isCompressionMode && !!compressionTargetId
    && Number.isFinite(targetMin) && Number.isFinite(targetMax)
    && targetMin < 0 && targetMax > 0;

  return { samples, gapStats, targetStraddlesZero };
};

// Lightweight stats for the optimizer. Returns TWO Cpk flavours:
//  - cp:      PARAMETRIC (min(USL-μ, μ-LSL)/3σ) — stable at any N, used to DRIVE
//             the search because the equivalent flavour saturates / is noisy.
//  - cpEquiv: the app's quantile/defect-based "Equiv. Cpk" (normSInv of per-side
//             defect rates) — what the result card REPORTS and targets, so the
//             solver's number matches the app's. The two differ because the
//             compression ratio (a ratio of normals) has heavier-than-normal
//             tails, so the defect-based Cpk runs below the μ/σ one.
// Shared defect-rate -> equivalent-Cpk conversion. Zero observed defects on a
// side can only support p < 3/N (rule of three, ~95% conf), so we report the
// Cpk LOWER BOUND normSInv(1 - 3/N)/3 and flag it, rather than a flat cap that
// would (a) claim resolution the sim lacks and (b) be discontinuous with the
// 1-defect case. Used by both ratioStats (solver) and calculateSimulationStats
// (result card) so their numbers agree.
const defectRateToCpk = (failCount: number, N: number): { value: number; bound: boolean } => {
  if (N <= 0) return { value: 0, bound: false };
  const p = failCount / N;
  if (p <= 0) return { value: normSInv(1 - 3 / N) / 3, bound: true };
  return { value: normSInv(1 - p) / 3, bound: false };
};

const ratioStats = (
  samples: Float32Array,
  lsl: number,
  usl: number
): { mean: number; std: number; cp: number; cpEquiv: number; yieldRate: number; defects: number } => {
  const N = samples.length;
  let sum = 0;
  let valid = 0;
  let pass = 0;
  let failLow = 0;
  let failHigh = 0;
  for (let i = 0; i < N; i++) {
    const v = samples[i];
    if (!Number.isFinite(v)) continue;
    sum += v;
    valid++;
    if (v < lsl) failLow++;
    else if (v > usl) failHigh++;
    else pass++;
  }
  if (valid === 0) return { mean: NaN, std: NaN, cp: 0, cpEquiv: 0, yieldRate: 0, defects: 0 };
  const mean = sum / valid;
  let sq = 0;
  for (let i = 0; i < N; i++) {
    const v = samples[i];
    if (!Number.isFinite(v)) continue;
    sq += (v - mean) * (v - mean);
  }
  const std = valid > 1 ? Math.sqrt(sq / (valid - 1)) : 0;
  const cp = std > 0
    ? Math.min(5.0, Math.min((usl - mean) / (3 * std), (mean - lsl) / (3 * std)))
    : 5.0;

  // Equivalent Cpk — via the SHARED defectRateToCpk helper (same rule-of-three
  // lower bound as calculateSimulationStats), so the solver's reported value is
  // reproducible on the result card. Worst (min) side wins.
  const cpL = defectRateToCpk(failLow, N).value;
  const cpH = defectRateToCpk(failHigh, N).value;
  const cpEquiv = Math.min(cpL, cpH);

  return { mean, std, cp, cpEquiv, yieldRate: (pass / N) * 100, defects: failLow + failHigh };
};


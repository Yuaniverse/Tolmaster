// localStorage JSON turns NaN into null. Restore those values to the same
// non-finite sentinel used by calculateSimulationStats for an all-invalid run.
const restoreNullableNumber = (value: unknown, fallback = 0): number => {
  if (value === null) return Number.NaN;
  return typeof value === 'number' ? value : fallback;
};

const restorePersistedResult = (value: unknown): SimulationResult | null => {
  if (!isRecord(value) || !Array.isArray(value.histogramData)) return null;
  if (typeof value.yieldRate !== 'number' || typeof value.ppm !== 'number') return null;

  const totalSampleCount = Math.max(0, Math.trunc(restoreNullableNumber(value.totalSampleCount)));
  const validSampleCount = Math.max(0, Math.trunc(restoreNullableNumber(value.validSampleCount)));
  const fitShiftInterferenceCount = Math.max(0, Math.trunc(restoreNullableNumber(value.fitShiftInterferenceCount)));
  const ratioUndefinedCount = Math.max(0, Math.trunc(restoreNullableNumber(value.ratioUndefinedCount)));
  const rawBreakdown = isRecord(value.failureBreakdown) ? value.failureBreakdown : {};
  const rawGapStats = isRecord(value.gapStats) ? value.gapStats : null;

  const histogramData = value.histogramData.filter(bin => {
    if (!isRecord(bin)) return false;
    return ['binStart', 'binEnd', 'mid', 'count'].every(key => typeof bin[key] === 'number');
  });

  return {
    mean: restoreNullableNumber(value.mean, Number.NaN),
    stdDev: restoreNullableNumber(value.stdDev),
    min: restoreNullableNumber(value.min, Number.NaN),
    max: restoreNullableNumber(value.max, Number.NaN),
    yieldRate: value.yieldRate,
    ppm: value.ppm,
    cp: restoreNullableNumber(value.cp),
    cpIsLowerBound: value.cpIsLowerBound === true,
    samples: [],
    histogramData,
    totalSampleCount,
    validSampleCount,
    fitShiftInterferenceCount,
    ratioUndefinedCount,
    compressionTargetStraddlesZero: typeof value.compressionTargetStraddlesZero === 'boolean'
      ? value.compressionTargetStraddlesZero
      : undefined,
    failHighCount: Math.max(0, Math.trunc(restoreNullableNumber(value.failHighCount))),
    failLowCount: Math.max(0, Math.trunc(restoreNullableNumber(value.failLowCount))),
    failureBreakdown: {
      fitShiftInterference: restoreNullableNumber(rawBreakdown.fitShiftInterference),
      ratioUndefined: restoreNullableNumber(rawBreakdown.ratioUndefined),
      upperSpec: restoreNullableNumber(rawBreakdown.upperSpec),
      lowerSpec: restoreNullableNumber(rawBreakdown.lowerSpec)
    },
    gapStats: rawGapStats ? {
      mean: restoreNullableNumber(rawGapStats.mean),
      min: restoreNullableNumber(rawGapStats.min),
      max: restoreNullableNumber(rawGapStats.max)
    } : undefined
  };
};

const loadPersistedResults = (projectIds: Set<string>): Record<string, SimulationResult> => {
  const saved = localStorage.getItem(RESULTS_STORAGE_KEY);
  if (!saved) return {};

  try {
    const parsed: unknown = JSON.parse(saved);
    if (!isRecord(parsed)) return {};

    // Accept the versioned shape and the unversioned map used by early builds.
    const rawResults = isRecord(parsed.results) ? parsed.results : parsed;
    const restored = Object.create(null) as Record<string, SimulationResult>;
    Object.entries(rawResults).forEach(([projectId, rawResult]) => {
      if (!projectIds.has(projectId)) return;
      const result = restorePersistedResult(rawResult);
      if (result) restored[projectId] = result;
    });
    return restored;
  } catch (err) {
    console.warn('Failed to load saved simulation results; ignoring corrupted data.', err);
    return {};
  }
};

// 將貼上/上傳的圖片等比縮到最大寬度並重新編碼，避免原始 CAD 截圖撐爆 localStorage。
// 優先用 WebP：CAD 截圖多是線條 + 文字 + 大片平坦色塊，WebP 在這種內容上比 JPEG 小得多
// （實測同觀感品質下約為 JPEG 的 1/3）。1400px 仍足以讓截圖中的標註文字清晰可讀。
const REF_IMAGE_MAX_WIDTH = 1400;
const WEBP_QUALITY = 0.75;
const JPEG_FALLBACK_QUALITY = 0.82;
async function compressImage(src: Blob | File): Promise<string> {
  const dataUrl: string = await new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result as string);
    reader.onerror = reject;
    reader.readAsDataURL(src);
  });
  const img = new window.Image();
  await new Promise<void>((resolve, reject) => {
    img.onload = () => resolve();
    img.onerror = reject;
    img.src = dataUrl;
  });
  const scale = img.width > REF_IMAGE_MAX_WIDTH ? REF_IMAGE_MAX_WIDTH / img.width : 1;
  const w = Math.round(img.width * scale);
  const h = Math.round(img.height * scale);
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext('2d');
  if (!ctx) return dataUrl; // 極少數不支援時退回原圖
  // 白底：JPEG 無透明，避免透明區變黑
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(0, 0, w, h);
  ctx.drawImage(img, 0, 0, w, h);
  // 不支援 WebP 的瀏覽器不會拋錯，而是靜默回傳 PNG —— 對截圖而言 PNG 遠大於 JPEG，
  // 等於反效果。所以必須檢查回傳的 MIME 前綴，確認真的拿到 WebP 才採用。
  const webp = canvas.toDataURL('image/webp', WEBP_QUALITY);
  if (webp.startsWith('data:image/webp')) return webp;
  return canvas.toDataURL('image/jpeg', JPEG_FALLBACK_QUALITY);
}


class ErrorBoundary extends React.Component<{ children: React.ReactNode }, { hasError: boolean, error: Error | null }> {
  constructor(props: { children: React.ReactNode }) {
    super(props);
    this.state = { hasError: false, error: null };
  }

  static getDerivedStateFromError(error: Error) {
    return { hasError: true, error };
  }

  componentDidCatch(error: Error, errorInfo: React.ErrorInfo) {
    console.error("ErrorBoundary caught an error", error, errorInfo);
  }

  render() {
    if (this.state.hasError) {
      return (
        <div className="p-8 bg-[var(--danger-soft)] text-[var(--ink-1)] border border-[var(--danger)]/35 rounded m-4">
          <h2 className="text-lg font-bold mb-2">Something went wrong.</h2>
          <p className="mb-4">The application crashed while rendering. Please try reloading the page.</p>
          <details className="whitespace-pre-wrap font-mono text-sm bg-[var(--surface)] p-4 border rounded">
            {this.state.error && this.state.error.toString()}
          </details>
          <button
            onClick={() => window.location.reload()}
            className="mt-4 px-4 py-2 bg-[var(--danger)] text-[var(--surface)] rounded hover:bg-[var(--danger)]"
          >
            Reload Page
          </button>
        </div>
      );
    }

    return this.props.children;
  }
}


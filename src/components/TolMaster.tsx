const generateId = () => Math.random().toString(36).substr(2, 9);

const formatNumber = (num: number, digits: number) => {
  const s = num.toFixed(digits);
  // Fix -0 display issue
  return parseFloat(s) === 0 ? Math.abs(parseFloat(s)).toFixed(digits) : s;
};

const randomNormal = (mean: number, stdDev: number) => {
  let u = 0, v = 0;
  while (u === 0) u = Math.random();
  while (v === 0) v = Math.random();
  const z = Math.sqrt(-2.0 * Math.log(u)) * Math.cos(2.0 * Math.PI * v);
  return mean + z * stdDev;
};

const randomBeta05 = () => {
  // Beta(0.5, 0.5) generator (Arcsine distribution)
  // Method: sin^2(Theta) where Theta is Uniform(0, PI/2)
  // Or simply: sin^2( (PI/2) * rand ) ? No, standard method is sin^2(PI/2 * U) is not quite right for Beta(0.5,0.5).
  // Actually, Beta(0.5, 0.5) is related to sin^2.
  // Let U ~ Uniform(0, 1). X = sin^2( (PI/2) * U ) is NOT Beta(0.5, 0.5).
  // Correct generation for Beta(alpha, beta):
  // For alpha=0.5, beta=0.5:
  // X = sin^2( 2 * PI * U ) ? No.
  // Let's use the standard Gamma method or a specific transformation.
  // For Beta(0.5, 0.5): X = sin^2( Phi ) where Phi is Uniform(0, PI/2) IS correct?
  // Let's check: If X ~ Beta(1/2, 1/2), then X is Arcsine distributed on [0,1].
  // CDF is (2/PI) * arcsin(sqrt(x)).
  // Inverse CDF method: u = (2/PI) * arcsin(sqrt(x)) => x = sin^2(u * PI / 2).
  // So yes, if U ~ Uniform(0, 1), then X = sin^2(U * PI / 2) follows Beta(0.5, 0.5).
  return Math.pow(Math.sin(Math.random() * Math.PI / 2), 2);
};

// Empirical sampler: Bootstrap resampling from measured data
// Preserves skew, tails, and multimodality without smoothing or fitting
const sampleEmpirical = (model: EmpiricalModel): number => {
  const i = Math.floor(Math.random() * model.n);
  return model.samples[i];
};

const calculateSigma = (tolPlus: number, tolMinus: number, dist: DistributionType, cp?: number): number => {
  if (dist === 'Fixed') return 0;
  const totalRange = tolPlus + tolMinus;
  const halfRange = totalRange / 2;

  if (dist === 'Uniform') {
    return totalRange / Math.sqrt(12);
  }

  if (cp && cp > 0) {
    return halfRange / (3 * cp);
  } else {
    return halfRange / 3;
  }
};

const calculateEffectiveMean = (nominal: number, tolPlus: number, tolMinus: number): number => {
  return nominal + (tolPlus - tolMinus) / 2;
};

const getWarning = (valStr: string, type: 'Tolerance'): string | null => {
  if (/^0\d+/.test(valStr)) {
    return "Suspected missing decimal point (e.g. 0.15?)";
  }
  const val = parseFloat(valStr);
  if (!isNaN(val) && val > 3.0) {
    return "Large tolerance value detected (> 3.0). Verify if correct.";
  }
  return null;
};

// Inverse Standard Normal Distribution (Acklam's approximation)
// Used to convert yield rate back to equivalent CP
const normSInv = (p: number): number => {
  const a1 = -3.969683028665376e+01;
  const a2 = 2.209460984245205e+02;
  const a3 = -2.759285104469687e+02;
  const a4 = 1.383577518672690e+02;
  const a5 = -3.066479806614716e+01;
  const a6 = 2.506628277459239e+00;

  const b1 = -5.447609879822406e+01;
  const b2 = 1.615858368580409e+02;
  const b3 = -1.556989798598866e+02;
  const b4 = 6.680131188771972e+01;
  const b5 = -1.328068155288572e+01;

  const c1 = -7.784894002430293e-03;
  const c2 = -3.223964580411365e-01;
  const c3 = -2.400758277161838e+00;
  const c4 = -2.549732539343734e+00;
  const c5 = 4.374664141464968e+00;
  const c6 = 2.938163982698783e+00;

  const d1 = 7.784695709041462e-03;
  const d2 = 3.224671290700398e-01;
  const d3 = 2.445134137142996e+00;
  const d4 = 3.754408661907416e+00;

  const p_low = 0.02425;
  const p_high = 1 - p_low;

  let q, r;

  if (p < 0 || p > 1) {
    return NaN;
  } else if (p < p_low) {
    q = Math.sqrt(-2 * Math.log(p));
    return (((((c1 * q + c2) * q + c3) * q + c4) * q + c5) * q + c6) /
      ((((d1 * q + d2) * q + d3) * q + d4) * q + 1);
  } else if (p <= p_high) {
    q = p - 0.5;
    r = q * q;
    return (((((a1 * r + a2) * r + a3) * r + a4) * r + a5) * r + a6) * q /
      (((((b1 * r + b2) * r + b3) * r + b4) * r + b5) * r + 1);
  } else {
    q = Math.sqrt(-2 * Math.log(1 - p));
    return -(((((c1 * q + c2) * q + c3) * q + c4) * q + c5) * q + c6) /
      ((((d1 * q + d2) * q + d3) * q + d4) * q + 1);
  }
};


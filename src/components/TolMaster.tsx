const isQuotaError = (err: unknown): boolean =>
  err instanceof DOMException &&
  (err.name === 'QuotaExceededError' || err.name === 'NS_ERROR_DOM_QUOTA_REACHED');

// localStorage 以 UTF-16 儲存，每字元 2 bytes。鍵名本身也計入配額。
const estimateLocalStorageBytes = (): { total: number; byKey: Record<string, number> } => {
  const byKey: Record<string, number> = {};
  let total = 0;
  if (typeof window === 'undefined') return { total, byKey };
  try {
    for (let i = 0; i < localStorage.length; i++) {
      const key = localStorage.key(i);
      if (key === null) continue;
      const bytes = (key.length + (localStorage.getItem(key)?.length ?? 0)) * 2;
      byKey[key] = bytes;
      total += bytes;
    }
  } catch (err) {
    console.warn('Failed to estimate localStorage usage.', err);
  }
  return { total, byKey };
};


const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

// EmpiricalModel.samples 是 Float32Array，而 JSON.stringify 不認識 TypedArray —— 它會序列化成
// {"0":10.100000381469727,"1":9.899999618530273,...}：除了多出索引鍵，Float32 轉回 double 還會
// 產生一長串無意義的小數，整體膨脹 4–5 倍。存檔前壓成純陣列並收斂到 6 位小數（Float32 有效位數
// 約 7 位，不會有實質精度損失），單一樣本從約 25 bytes 降到約 8 bytes。
//
// 三種來源形狀都要吃得下：Float32Array（記憶體中）、number[]（新格式）、
// {"0":..} 物件（舊版存檔）。
const packEmpiricalSamples = (value: unknown): number[] => {
  const out: number[] = [];
  const push = (raw: unknown) => {
    const num = typeof raw === 'number' ? raw : Number(raw);
    if (Number.isFinite(num)) out.push(Number(num.toFixed(6)));
  };

  if (value instanceof Float32Array || Array.isArray(value)) {
    for (let i = 0; i < value.length; i++) push(value[i]);
  } else if (isRecord(value)) {
    // 依數字索引排序，不能依賴物件鍵的列舉順序
    Object.keys(value)
      .map(Number)
      .filter(k => Number.isInteger(k) && k >= 0)
      .sort((a, b) => a - b)
      .forEach(k => push(value[String(k)]));
  }
  return out;
};

const unpackEmpiricalSamples = (value: unknown): Float32Array =>
  value instanceof Float32Array ? value : Float32Array.from(packEmpiricalSamples(value));

// JSON.stringify 的 replacer 會拿到未經轉換的原始屬性值，所以能在樹中任何位置攔截
// Float32Array，不需要手動深走整個結構。存檔與匯出都要用，否則膨脹會從其中一條路徑漏回來。
const float32Replacer = (_key: string, value: unknown) =>
  value instanceof Float32Array ? packEmpiricalSamples(value) : value;


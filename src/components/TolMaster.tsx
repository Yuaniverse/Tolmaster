    const mean = validSampleCount > 0 ? sum / validSampleCount : NaN;

    let sumSqDiff = 0;
    for (let i = 0; i < N; i++) {
      const diff = samples[i] - mean;
      if (!Number.isFinite(diff)) continue;
      sumSqDiff += (diff * diff);
    }
    const stdDev = validSampleCount > 1 ? Math.sqrt(sumSqDiff / (validSampleCount - 1)) : 0;

    // Histogram

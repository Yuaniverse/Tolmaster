// 把內嵌在 project 物件裡的 referenceImage 抽成獨立 map。舊版存檔的自動遷移與
// 匯入檔案的拆解共用這段邏輯 —— 兩者面對的資料形狀完全相同。
// 冪等：projects 上已無 referenceImage 時回傳 hadInlineImages: false。
const splitInlineImages = (
  projects: AnalysisProject[]
): { projects: AnalysisProject[]; images: ReferenceImageMap; hadInlineImages: boolean } => {
  const images: ReferenceImageMap = {};
  let hadInlineImages = false;
  const stripped = projects.map(project => {
    const inline = project?.referenceImage;
    if (typeof inline !== 'string' || !inline) return project;
    hadInlineImages = true;
    images[project.id] = inline;
    const rest = { ...project };
    delete rest.referenceImage;
    return rest;
  });
  return { projects: hadInlineImages ? stripped : projects, images, hadInlineImages };
};

// 把舊存檔中內嵌的圖片搬進獨立 key。回傳 false 代表搬不動，呼叫端應維持 legacy 內嵌模式。
//
// 寫入順序刻意讓圖片「同時存在於兩個 key」而非「都不在」：中途當掉頂多重複一份，不會遺失。
const migrateInlineImages = (
  strippedProjects: AnalysisProject[],
  images: ReferenceImageMap
): boolean => {
  try {
    localStorage.setItem(IMAGES_STORAGE_KEY, JSON.stringify(images));
    localStorage.setItem(PROJECTS_STORAGE_KEY, serializeProjectsForStorage(strippedProjects));
    return true;
  } catch (err) {
    if (!isQuotaError(err)) {
      console.error('Failed to migrate reference images.', err);
      return false;
    }
  }

  // 整包搬會讓所有圖片短暫同時存在於兩個 key，用量翻倍。配額不足時改逐張搬：
  // 每搬一張就立刻把它從 projects 移除以釋放空間，峰值額外用量僅一張圖。
  try {
    const moved: ReferenceImageMap = {};
    const stillInline = new Map(Object.entries(images));
    for (const [projectId, dataUrl] of Object.entries(images)) {
      moved[projectId] = dataUrl;
      localStorage.setItem(IMAGES_STORAGE_KEY, JSON.stringify(moved));
      stillInline.delete(projectId);
      const partial = strippedProjects.map(project => {
        const inline = stillInline.get(project.id);
        return inline ? { ...project, referenceImage: inline } : project;
      });
      localStorage.setItem(PROJECTS_STORAGE_KEY, serializeProjectsForStorage(partial));
    }
    return true;
  } catch (err) {
    console.warn('Incremental reference image migration failed; keeping inline images.', err);
    return false;
  }
};

const reviveProjectEmpiricalModels = (project: AnalysisProject): AnalysisProject => {
  if (!Array.isArray(project?.items)) return project;
  let changed = false;
  const items = project.items.map(item => {
    const model = item?.empiricalModel;
    if (!model) return item;
    const samples = unpackEmpiricalSamples(model.samples);
    if (samples === model.samples) return item;
    changed = true;
    return { ...item, empiricalModel: { ...model, samples } };
  });
  return changed ? { ...project, items } : project;
};


let _normalSpare: number | null = null;
const randomNormal = (mean: number, stdDev: number) => {
  if (_normalSpare !== null) {
    const val = mean + _normalSpare * stdDev;
    _normalSpare = null;
    return val;
  }
  let u = 0, v = 0;
  while (u === 0) u = Math.random();
  while (v === 0) v = Math.random();
  const mag = Math.sqrt(-2.0 * Math.log(u));
  _normalSpare = mag * Math.sin(2.0 * Math.PI * v);
  return mean + mag * Math.cos(2.0 * Math.PI * v) * stdDev;
};

const randomBeta05 = () => {
  // Beta(0.5, 0.5) generator (Arcsine distribution)
  // Method: sin^2(Theta) where Theta is Uniform(0, PI/2)
  // Or simply: sin^2( (PI/2) * rand ) ? No, standard method is sin^2(PI/2 * U) is not quite right for Beta(0.5,0.5).
  // Actually, Beta(0.5, 0.5) is related to sin^2.
  // Let U ~ Uniform(0, 1). X = sin^2( (PI/2) * U ) is NOT Beta(0.5, 0.5).
  // Correct generation for Beta(alpha, beta):
  // For alpha=0.5, beta=0.5:
  // X = sin^2( 2 * PI * U ) ? No.
  // Let's use the standard Gamma method or a specific transformation.
  // For Beta(0.5, 0.5): X = sin^2( Phi ) where Phi is Uniform(0, PI/2) IS correct?
  // Let's check: If X ~ Beta(1/2, 1/2), then X is Arcsine distributed on [0,1].
  // CDF is (2/PI) * arcsin(sqrt(x)).
  // Inverse CDF method: u = (2/PI) * arcsin(sqrt(x)) => x = sin^2(u * PI / 2).
  // So yes, if U ~ Uniform(0, 1), then X = sin^2(U * PI / 2) follows Beta(0.5, 0.5).
  return Math.pow(Math.sin(Math.random() * Math.PI / 2), 2);
};

// Empirical sampler: Bootstrap resampling from measured data
// Preserves skew, tails, and multimodality without smoothing or fitting
const sampleEmpirical = (model: EmpiricalModel): number => {
  const i = Math.floor(Math.random() * model.n);
  return model.samples[i];
};

const calculateSigma = (tolPlus: number, tolMinus: number, dist: DistributionType, cp?: number): number => {
  if (dist === 'Fixed') return 0;
  const totalRange = tolPlus + tolMinus;
  const halfRange = totalRange / 2;

  if (dist === 'Uniform') {
    return totalRange / Math.sqrt(12);
  }

  if (cp && cp > 0) {
    return halfRange / (3 * cp);
  } else {
    return halfRange / 3;
  }
};

const calculateEffectiveMean = (nominal: number, tolPlus: number, tolMinus: number): number => {
  return nominal + (tolPlus - tolMinus) / 2;
};

const calculateFitShiftVariance = (fitParams: FitParams): number => {
  const holeMean = calculateEffectiveMean(fitParams.holeNom, fitParams.holeTolPlus, fitParams.holeTolMinus);
  const shaftMean = calculateEffectiveMean(fitParams.shaftNom, fitParams.shaftTolPlus, fitParams.shaftTolMinus);
  const holeSigma = calculateSigma(fitParams.holeTolPlus, fitParams.holeTolMinus, fitParams.holeDist, fitParams.holeCP);
  const shaftSigma = calculateSigma(fitParams.shaftTolPlus, fitParams.shaftTolMinus, fitParams.shaftDist, fitParams.shaftCP);
  const muGap = holeMean - shaftMean;
  const gapSecondMomentApprox = (muGap * muGap) + (holeSigma * holeSigma) + (shaftSigma * shaftSigma);

  // Analytic RSS/sensitivity use the untruncated E[gap^2] approximation.
  // FitShift interference is handled separately by Monte Carlo failure accounting.
  return fitParams.shiftDist === 'Beta0.5'
    ? gapSecondMomentApprox / 8
    : gapSecondMomentApprox / 12;
};

// Clear compressionTargetId when it no longer points at a valid, selectable
// target: a deleted/missing item, or a FitShift item (whose `nominal` the sampler
// ignores, so it can never act as a real compression denominator). Centralised
// here and applied on every load/import path so a dangling or invalid reference
// can never reach the Monte Carlo core, where a ~0 denominator would invalidate
// every sample and be misread as a total-failure run.
const normalizeCompressionTarget = <T extends { compressionTargetId?: string | null; items: ToleranceItem[] }>(project: T): T => {
  const id = project.compressionTargetId;
  if (!id) return project;
  const target = project.items.find(it => it.id === id);
  if (!target || target.type === 'FitShift') {
    return { ...project, compressionTargetId: null };
  }
  return project;
};

